SELECT jsonb_pretty(jsonb_build_object(
  'tables', (
    SELECT jsonb_agg(jsonb_build_object('table_name', c.relname, 'rls_enabled', c.relrowsecurity) ORDER BY c.relname)
    FROM pg_class c
    JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relname IN ('notices','events')
  ),
  'policies', (
    SELECT COALESCE(jsonb_agg(jsonb_build_object('table_name', tablename,'policy_name',policyname,'cmd',cmd,'roles',roles,'qual',qual,'with_check',with_check) ORDER BY tablename,policyname),'[]'::jsonb)
    FROM pg_policies
    WHERE schemaname='public' AND tablename IN ('notices','events')
  ),
  'notices', (SELECT count(*) FROM public.notices),
  'events', (SELECT count(*) FROM public.events)
)) AS step12_operating_result;
