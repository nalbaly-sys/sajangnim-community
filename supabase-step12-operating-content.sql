CREATE TABLE IF NOT EXISTS public.notices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL CHECK (char_length(trim(title)) BETWEEN 2 AND 150),
  content text NOT NULL CHECK (char_length(trim(content)) BETWEEN 2 AND 10000),
  status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  is_pinned boolean NOT NULL DEFAULT false,
  created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL CHECK (char_length(trim(title)) BETWEEN 2 AND 150),
  content text NOT NULL CHECK (char_length(trim(content)) BETWEEN 2 AND 10000),
  status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','ENDED','ARCHIVED')),
  starts_at timestamptz,
  ends_at timestamptz,
  created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  CONSTRAINT events_date_order CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at >= starts_at)
);

ALTER TABLE public.notices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS notices_public_select ON public.notices;
CREATE POLICY notices_public_select ON public.notices
FOR SELECT TO anon, authenticated
USING (status = 'PUBLISHED');

DROP POLICY IF EXISTS notices_admin_select ON public.notices;
CREATE POLICY notices_admin_select ON public.notices
FOR SELECT TO authenticated
USING (public.is_active_admin());

DROP POLICY IF EXISTS notices_admin_insert ON public.notices;
CREATE POLICY notices_admin_insert ON public.notices
FOR INSERT TO authenticated
WITH CHECK (public.is_active_admin() AND created_by = (SELECT auth.uid()));

DROP POLICY IF EXISTS notices_admin_update ON public.notices;
CREATE POLICY notices_admin_update ON public.notices
FOR UPDATE TO authenticated
USING (public.is_active_admin())
WITH CHECK (public.is_active_admin());

DROP POLICY IF EXISTS notices_admin_delete ON public.notices;
CREATE POLICY notices_admin_delete ON public.notices
FOR DELETE TO authenticated
USING (public.is_active_admin());

DROP POLICY IF EXISTS events_public_select ON public.events;
CREATE POLICY events_public_select ON public.events
FOR SELECT TO anon, authenticated
USING (status = 'PUBLISHED');

DROP POLICY IF EXISTS events_admin_select ON public.events;
CREATE POLICY events_admin_select ON public.events
FOR SELECT TO authenticated
USING (public.is_active_admin());

DROP POLICY IF EXISTS events_admin_insert ON public.events;
CREATE POLICY events_admin_insert ON public.events
FOR INSERT TO authenticated
WITH CHECK (public.is_active_admin() AND created_by = (SELECT auth.uid()));

DROP POLICY IF EXISTS events_admin_update ON public.events;
CREATE POLICY events_admin_update ON public.events
FOR UPDATE TO authenticated
USING (public.is_active_admin())
WITH CHECK (public.is_active_admin());

DROP POLICY IF EXISTS events_admin_delete ON public.events;
CREATE POLICY events_admin_delete ON public.events
FOR DELETE TO authenticated
USING (public.is_active_admin());

REVOKE ALL ON TABLE public.notices FROM PUBLIC;
REVOKE ALL ON TABLE public.events FROM PUBLIC;
REVOKE ALL ON TABLE public.notices FROM anon;
REVOKE ALL ON TABLE public.events FROM anon;
REVOKE ALL ON TABLE public.notices FROM authenticated;
REVOKE ALL ON TABLE public.events FROM authenticated;

GRANT SELECT ON TABLE public.notices TO anon, authenticated;
GRANT SELECT ON TABLE public.events TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.notices TO authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.events TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.notices_id_seq TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.events_id_seq TO authenticated;

