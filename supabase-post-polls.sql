-- 기간제 게시글 투표 기능
-- 실제 Supabase 프로젝트에 적용된 최종 구조와 동일한 기준

create table if not exists public.post_polls (
  id bigint generated by default as identity primary key,
  post_id bigint not null unique references public.posts(id) on delete cascade,
  question text not null check (char_length(question) between 2 and 200),
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  check (ends_at > created_at)
);

create table if not exists public.poll_options (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.post_polls(id) on delete cascade,
  option_text text not null check (char_length(option_text) between 1 and 100),
  position integer not null check (position between 1 and 6),
  created_at timestamptz not null default now(),
  unique (poll_id, position),
  unique (id, poll_id)
);

create table if not exists public.poll_votes (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.post_polls(id) on delete cascade,
  option_id bigint not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (poll_id, user_id),
  foreign key (option_id, poll_id) references public.poll_options(id, poll_id) on delete cascade
);

create index if not exists post_polls_post_id_idx on public.post_polls(post_id);
create index if not exists poll_options_poll_id_idx on public.poll_options(poll_id, position);
create index if not exists poll_votes_poll_id_idx on public.poll_votes(poll_id);
create index if not exists poll_votes_user_id_idx on public.poll_votes(user_id);

alter table public.post_polls enable row level security;
alter table public.poll_options enable row level security;
alter table public.poll_votes enable row level security;

grant select, insert, delete on public.post_polls to authenticated;
grant select on public.post_polls to anon;
grant select, insert, delete on public.poll_options to authenticated;
grant select on public.poll_options to anon;
grant select, insert on public.poll_votes to authenticated;

-- 기존 posts/comments/reactions/reports 등도 public sequence를 사용하므로
-- 투표 기능 추가 시 기존 등록 기능의 sequence 권한을 유지한다.
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists post_polls_public_select on public.post_polls;
create policy post_polls_public_select on public.post_polls
for select to anon, authenticated
using (exists (
  select 1 from public.posts p
  where p.id = post_id and p.status = 'ACTIVE'
));

drop policy if exists post_polls_owner_insert on public.post_polls;
create policy post_polls_owner_insert on public.post_polls
for insert to authenticated
with check (
  ends_at > now()
  and exists (
    select 1 from public.posts p
    where p.id = post_id
      and p.user_id = (select auth.uid())
      and p.status = 'ACTIVE'
  )
);

drop policy if exists post_polls_owner_delete on public.post_polls;
create policy post_polls_owner_delete on public.post_polls
for delete to authenticated
using (exists (
  select 1 from public.posts p
  where p.id = post_id and p.user_id = (select auth.uid())
));

drop policy if exists poll_options_public_select on public.poll_options;
create policy poll_options_public_select on public.poll_options
for select to anon, authenticated
using (exists (
  select 1
  from public.post_polls pp
  join public.posts p on p.id = pp.post_id
  where pp.id = poll_id and p.status = 'ACTIVE'
));

drop policy if exists poll_options_owner_insert on public.poll_options;
create policy poll_options_owner_insert on public.poll_options
for insert to authenticated
with check (exists (
  select 1
  from public.post_polls pp
  join public.posts p on p.id = pp.post_id
  where pp.id = poll_id
    and p.user_id = (select auth.uid())
    and p.status = 'ACTIVE'
    and pp.ends_at > now()
));

drop policy if exists poll_options_owner_delete on public.poll_options;
create policy poll_options_owner_delete on public.poll_options
for delete to authenticated
using (exists (
  select 1
  from public.post_polls pp
  join public.posts p on p.id = pp.post_id
  where pp.id = poll_id and p.user_id = (select auth.uid())
));

drop policy if exists poll_votes_own_select on public.poll_votes;
create policy poll_votes_own_select on public.poll_votes
for select to authenticated
using (user_id = (select auth.uid()));

drop policy if exists poll_votes_own_insert on public.poll_votes;
create policy poll_votes_own_insert on public.poll_votes
for insert to authenticated
with check (
  user_id = (select auth.uid())
  and exists (
    select 1
    from public.post_polls pp
    join public.posts p on p.id = pp.post_id
    where pp.id = poll_id
      and pp.ends_at > now()
      and p.status = 'ACTIVE'
  )
);

drop view if exists public.poll_option_results;
create view public.poll_option_results as
select
  o.poll_id,
  o.id as option_id,
  o.option_text,
  o.position,
  count(v.id)::bigint as vote_count
from public.poll_options o
join public.post_polls pp on pp.id = o.poll_id
join public.posts p on p.id = pp.post_id and p.status = 'ACTIVE'
left join public.poll_votes v
  on v.poll_id = o.poll_id and v.option_id = o.id
where pp.ends_at <= now()
group by o.poll_id, o.id, o.option_text, o.position;

revoke all on public.poll_option_results from public;
grant select on public.poll_option_results to anon, authenticated;
