-- 실제 Supabase 프로젝트 적용 완료 기준 기록

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  notification_type text not null check (notification_type in ('COMMENT','REPLY','REACTION')),
  post_id bigint not null references public.posts(id) on delete cascade,
  comment_id bigint references public.comments(id) on delete cascade,
  reaction_type text,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notifications_recipient_created_idx on public.notifications(recipient_id, created_at desc);
create index if not exists notifications_recipient_unread_idx on public.notifications(recipient_id, is_read, created_at desc);
create unique index if not exists notifications_comment_once_idx on public.notifications(recipient_id, notification_type, comment_id) where comment_id is not null and notification_type in ('COMMENT','REPLY');
create unique index if not exists notifications_reaction_once_idx on public.notifications(recipient_id, actor_id, post_id, notification_type, reaction_type) where notification_type='REACTION';

alter table public.notifications enable row level security;
revoke all on table public.notifications from anon, authenticated;
grant select on table public.notifications to authenticated;
grant update(is_read) on table public.notifications to authenticated;

create policy "notifications_select_own" on public.notifications for select to authenticated using ((select auth.uid())=recipient_id);
create policy "notifications_update_own" on public.notifications for update to authenticated using ((select auth.uid())=recipient_id) with check ((select auth.uid())=recipient_id);

create or replace function public.create_comment_notification()
returns trigger language plpgsql security definer set search_path=''
as $$
declare v_post_owner uuid; v_parent_owner uuid;
begin
  if new.status<>'ACTIVE' then return new; end if;
  select p.user_id into v_post_owner from public.posts p where p.id=new.post_id;
  if new.parent_comment_id is not null then select c.user_id into v_parent_owner from public.comments c where c.id=new.parent_comment_id; end if;
  if v_post_owner is not null and v_post_owner<>new.user_id then
    if new.parent_comment_id is not null and v_parent_owner=v_post_owner then
      insert into public.notifications(recipient_id,actor_id,notification_type,post_id,comment_id) values(v_post_owner,new.user_id,'REPLY',new.post_id,new.id) on conflict do nothing;
    else
      insert into public.notifications(recipient_id,actor_id,notification_type,post_id,comment_id) values(v_post_owner,new.user_id,'COMMENT',new.post_id,new.id) on conflict do nothing;
    end if;
  end if;
  if new.parent_comment_id is not null and v_parent_owner is not null and v_parent_owner<>new.user_id and v_parent_owner is distinct from v_post_owner then
    insert into public.notifications(recipient_id,actor_id,notification_type,post_id,comment_id) values(v_parent_owner,new.user_id,'REPLY',new.post_id,new.id) on conflict do nothing;
  end if;
  return new;
end;$$;
revoke all on function public.create_comment_notification() from public,anon,authenticated;
drop trigger if exists trg_create_comment_notification on public.comments;
create trigger trg_create_comment_notification after insert on public.comments for each row execute function public.create_comment_notification();

create or replace function public.create_reaction_notification()
returns trigger language plpgsql security definer set search_path=''
as $$
declare v_post_owner uuid;
begin
  select p.user_id into v_post_owner from public.posts p where p.id=new.post_id;
  if v_post_owner is null or v_post_owner=new.user_id then return new; end if;
  insert into public.notifications(recipient_id,actor_id,notification_type,post_id,reaction_type,is_read,created_at)
  values(v_post_owner,new.user_id,'REACTION',new.post_id,new.reaction_type,false,now())
  on conflict (recipient_id,actor_id,post_id,notification_type,reaction_type) where notification_type='REACTION'
  do update set is_read=false,created_at=excluded.created_at;
  return new;
end;$$;
revoke all on function public.create_reaction_notification() from public,anon,authenticated;
drop trigger if exists trg_create_reaction_notification on public.reactions;
create trigger trg_create_reaction_notification after insert on public.reactions for each row execute function public.create_reaction_notification();
