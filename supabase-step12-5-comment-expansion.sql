-- ============================================================
-- STEP 12.5 댓글 확장: 답글 + 댓글 공감
-- 목표
-- 1) comments에 parent_comment_id / reply_to_user_id 추가
-- 2) comment_reactions 신규 생성
-- 3) 기존 댓글 수정/삭제/신고 구조 유지
-- 4) 일반 회원은 ACTIVE 댓글에만 답글/공감 가능
-- 5) 본인 공감만 취소 가능
-- 6) 관리자 조회 정책 유지
-- ============================================================

BEGIN;

-- A. comments 확장
ALTER TABLE public.comments
  ADD COLUMN IF NOT EXISTS parent_comment_id bigint NULL,
  ADD COLUMN IF NOT EXISTS reply_to_user_id uuid NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname='comments_parent_comment_id_fkey'
      AND conrelid='public.comments'::regclass
  ) THEN
    ALTER TABLE public.comments
      ADD CONSTRAINT comments_parent_comment_id_fkey
      FOREIGN KEY (parent_comment_id)
      REFERENCES public.comments(id)
      ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_comments_parent_comment_id
  ON public.comments(parent_comment_id);
CREATE INDEX IF NOT EXISTS idx_comments_reply_to_user_id
  ON public.comments(reply_to_user_id);

-- B. 댓글 공감 테이블
CREATE TABLE IF NOT EXISTS public.comment_reactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comment_id bigint NOT NULL REFERENCES public.comments(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  reaction_type text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT comment_reactions_type_check
    CHECK (reaction_type IN ('공감','웃김','나도 겪음','열받음','힘내세요')),
  CONSTRAINT comment_reactions_unique UNIQUE (comment_id,user_id,reaction_type)
);

CREATE INDEX IF NOT EXISTS idx_comment_reactions_comment_id
  ON public.comment_reactions(comment_id);
CREATE INDEX IF NOT EXISTS idx_comment_reactions_user_id
  ON public.comment_reactions(user_id);

ALTER TABLE public.comment_reactions ENABLE ROW LEVEL SECURITY;

-- C. comment_reactions RLS
DROP POLICY IF EXISTS comment_reactions_select_all ON public.comment_reactions;
DROP POLICY IF EXISTS comment_reactions_public_select ON public.comment_reactions;
DROP POLICY IF EXISTS comment_reactions_admin_select ON public.comment_reactions;
DROP POLICY IF EXISTS comment_reactions_insert_own ON public.comment_reactions;
DROP POLICY IF EXISTS comment_reactions_delete_own ON public.comment_reactions;

CREATE POLICY comment_reactions_public_select
ON public.comment_reactions
FOR SELECT
TO anon, authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.comments c
    JOIN public.posts p ON p.id=c.post_id
    WHERE c.id=comment_id
      AND c.status='ACTIVE'
      AND p.status='ACTIVE'
  )
);

CREATE POLICY comment_reactions_admin_select
ON public.comment_reactions
FOR SELECT
TO authenticated
USING (public.is_active_admin());

CREATE POLICY comment_reactions_insert_own
ON public.comment_reactions
FOR INSERT
TO authenticated
WITH CHECK (
  user_id=(SELECT auth.uid())
  AND EXISTS (
    SELECT 1 FROM public.comments c
    JOIN public.posts p ON p.id=c.post_id
    WHERE c.id=comment_id
      AND c.status='ACTIVE'
      AND p.status='ACTIVE'
  )
);

CREATE POLICY comment_reactions_delete_own
ON public.comment_reactions
FOR DELETE
TO authenticated
USING (user_id=(SELECT auth.uid()));

-- D. comments 답글 INSERT 무결성 보호
CREATE OR REPLACE FUNCTION public.protect_comment_reply_fields()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=''
AS $$
DECLARE
  v_parent public.comments%ROWTYPE;
BEGIN
  IF NEW.parent_comment_id IS NULL THEN
    NEW.reply_to_user_id := NULL;
    RETURN NEW;
  END IF;

  SELECT * INTO v_parent
  FROM public.comments
  WHERE id=NEW.parent_comment_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION '답글 대상 댓글을 찾을 수 없습니다.' USING ERRCODE='23503';
  END IF;

  IF v_parent.post_id <> NEW.post_id OR v_parent.status <> 'ACTIVE' THEN
    RAISE EXCEPTION '답글을 작성할 수 없는 댓글입니다.' USING ERRCODE='42501';
  END IF;

  NEW.reply_to_user_id := v_parent.user_id;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.protect_comment_reply_fields() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.protect_comment_reply_fields() FROM anon;
REVOKE ALL ON FUNCTION public.protect_comment_reply_fields() FROM authenticated;

DROP TRIGGER IF EXISTS trg_protect_comment_reply_fields ON public.comments;
CREATE TRIGGER trg_protect_comment_reply_fields
BEFORE INSERT ON public.comments
FOR EACH ROW
EXECUTE FUNCTION public.protect_comment_reply_fields();

DROP POLICY IF EXISTS comments_insert_reply_own ON public.comments;
CREATE POLICY comments_insert_reply_own
ON public.comments
FOR INSERT
TO authenticated
WITH CHECK (
  user_id=(SELECT auth.uid())
  AND status='ACTIVE'
  AND EXISTS (
    SELECT 1 FROM public.posts p
    WHERE p.id=post_id AND p.status='ACTIVE'
  )
);

-- E. 최소 권한
REVOKE ALL ON TABLE public.comment_reactions FROM anon;
REVOKE ALL ON TABLE public.comment_reactions FROM authenticated;
GRANT SELECT ON TABLE public.comment_reactions TO anon, authenticated;
GRANT INSERT (comment_id,user_id,reaction_type) ON TABLE public.comment_reactions TO authenticated;
GRANT DELETE ON TABLE public.comment_reactions TO authenticated;

GRANT INSERT (post_id,user_id,content,is_anonymous,status,parent_comment_id,reply_to_user_id)
  ON TABLE public.comments TO authenticated;

COMMIT;

-- F. 실행 결과 확인
WITH cols AS (
  SELECT jsonb_agg(jsonb_build_object('column_name',column_name,'data_type',data_type) ORDER BY ordinal_position) AS data
  FROM information_schema.columns
  WHERE table_schema='public' AND table_name='comments'
    AND column_name IN ('parent_comment_id','reply_to_user_id')
), tbl AS (
  SELECT jsonb_build_object('table_name',c.relname,'rls_enabled',c.relrowsecurity) AS data
  FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
  WHERE n.nspname='public' AND c.relname='comment_reactions'
), pol AS (
  SELECT jsonb_agg(jsonb_build_object(
    'table_name',tablename,'policy_name',policyname,'cmd',cmd,'roles',roles,'qual',qual,'with_check',with_check
  ) ORDER BY tablename,cmd,policyname) AS data
  FROM pg_policies
  WHERE schemaname='public' AND tablename IN ('comments','comment_reactions')
)
SELECT jsonb_pretty(jsonb_build_object(
  'comment_columns',COALESCE((SELECT data FROM cols),'[]'::jsonb),
  'comment_reactions',(SELECT data FROM tbl),
  'policies',COALESCE((SELECT data FROM pol),'[]'::jsonb)
)) AS step12_5_comment_result;
